// Generates src/api-types.ts from the backend's OpenAPI document (response models: src/openx_workbench/api_schemas.py).
// Usage: npm run gen:api   (CI regenerates it and fails when the committed file differs)
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import { python } from "./demo-server.mjs";

const WEB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const REPO = path.resolve(WEB, "..");
const OUT = path.join(WEB, "src", "api-types.ts");

// Importing the app touches no data, but point it at an empty folder anyway.
const dataDir = fs.mkdtempSync(path.join(os.tmpdir(), "openx-openapi-"));
const dumped = spawnSync(python(), ["-c", "import json; from openx_workbench.api import app; print(json.dumps(app.openapi()))"], {
  env: { ...process.env, OPENX_DATA_DIR: dataDir, PYTHONUTF8: "1", PYTHONPATH: [path.join(REPO, "src"), process.env.PYTHONPATH].filter(Boolean).join(path.delimiter) },
  encoding: "utf8",
  maxBuffer: 64 * 1024 * 1024,
});
fs.rmSync(dataDir, { recursive: true, force: true });
if (dumped.status !== 0) throw new Error(`Could not read the OpenAPI document:\n${dumped.stderr}`);

const ast = await openapiTS(JSON.parse(dumped.stdout), { alphabetize: true, defaultNonNullable: false });
const header = "// Generated by web/scripts/gen-api-types.mjs from the backend's OpenAPI document. Do not edit.\n\n";
fs.writeFileSync(OUT, header + astToString(ast).replaceAll("\r\n", "\n"));
console.log(`wrote ${path.relative(WEB, OUT)}`);
